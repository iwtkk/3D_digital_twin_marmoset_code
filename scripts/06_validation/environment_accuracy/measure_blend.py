"""
I/O ledger: measure_blend   (runs inside Blender; called from make_table.py)

Purpose:
    Measure object dimensions and vertex distances in a .blend according to the measurement spec
    (spec JSON) and write the values to JSON. The computation is the same as object_dimensions.py /
    vertex.csv.py (world coordinates, m x 1000 = mm), except that the world matrix is recomputed from
    the parent hierarchy and matrix_basis instead of matrix_world (matrix_world of hidden objects can be stale).

Inputs:
    blend:
        type: file (.blend)
        note: the file opened with blender -b <blend>
    spec_json:
        type: file (JSON)
        content: {"rows": [ {label, method, object|a,b|top,bottom, axis, geometry?, ...}, ... ]}
                 method: bbox_extent | vertex_delta | bbox_gap | bbox_span
        note: generated by make_table.py from config/environment_table.yaml

Outputs:
    measured_json:
        type: file (JSON)
        content: {"blend": str, "blender_version": str,
                  "rows": [ {label, model_mm: float|null, error: str|null,
                             objects: [{name, n_vertices, hide_render, hide_viewport, collections,
                                        modifiers, constraints, animated, matrix_world_stale}]} ] }

Usage:
    blender -b <blend> --python measure_blend.py -- <spec_json> <measured_json>
"""
import json
import sys

import bpy
import mathutils

AXIS = {"x": 0, "y": 1, "z": 2}
STALE_TOL = 1e-6


def world_matrix(obj):
    """World matrix computed from the parent hierarchy and matrix_basis.

    Hidden (hide_viewport) objects are not evaluated by the depsgraph, so their saved matrix_world
    can be stale (in the 250430 version, the scale of Cube.002 is not applied).
    Therefore matrix_world is not used and the matrix is rebuilt every time. Constraints / drivers are ignored.
    """
    if obj.parent is None:
        return obj.matrix_basis.copy()
    return world_matrix(obj.parent) @ obj.matrix_parent_inverse @ obj.matrix_basis


def world_bbox(name, geometry="evaluated"):
    """geometry="evaluated": bound_box including modifiers (both halves for MIRROR)
    geometry="mesh":      mesh vertices before modifiers (one side of MIRROR = a single part)"""
    obj = bpy.data.objects[name]
    mw = world_matrix(obj)
    if geometry == "mesh":
        corners = [mw @ v.co for v in obj.data.vertices]
    elif geometry == "evaluated":
        corners = [mw @ mathutils.Vector(c) for c in obj.bound_box]
    else:
        raise ValueError(f"unknown geometry: {geometry}")
    mn = [min(v[i] for v in corners) * 1000 for i in range(3)]
    mx = [max(v[i] for v in corners) * 1000 for i in range(3)]
    return mn, mx


def world_vertex(name, index):
    obj = bpy.data.objects[name]
    n = len(obj.data.vertices)
    if not 0 <= index < n:
        raise IndexError(f"{name}: vertex {index} out of range (n={n})")
    return (world_matrix(obj) @ obj.data.vertices[index].co) * 1000


def object_info(name):
    obj = bpy.data.objects[name]
    return {
        "name": name,
        "n_vertices": len(obj.data.vertices) if obj.type == "MESH" else None,
        "hide_render": obj.hide_render,
        "hide_viewport": obj.hide_viewport,
        "collections": [c.name for c in obj.users_collection],
        "modifiers": [m.type for m in obj.modifiers],
        "constraints": [c.type for c in obj.constraints],
        # With animation, the position may change as frames advance (the measurement uses the saved state)
        "animated": bool(obj.animation_data and obj.animation_data.action),
        # The saved matrix_world differs from the recomputed matrix (= not evaluated)
        "matrix_world_stale": any(abs(a - b) > STALE_TOL
                                  for ra, rb in zip(obj.matrix_world, world_matrix(obj))
                                  for a, b in zip(ra, rb)),
    }


def measure(row):
    ax = AXIS[row["axis"]]
    method = row["method"]
    if method == "bbox_extent":
        names = [row["object"]]
        mn, mx = world_bbox(row["object"], row.get("geometry", "evaluated"))
        value = mx[ax] - mn[ax]
    elif method == "vertex_delta":
        (na, ia), (nb, ib) = row["a"], row["b"]
        names = [na] if na == nb else [na, nb]
        value = world_vertex(na, ia)[ax] - world_vertex(nb, ib)[ax]
    elif method == "bbox_gap":
        # face of a's bbox - face of b's bbox (side: min | max). E.g. ceiling bottom - floor top
        (na, sa), (nb, sb) = row["a"], row["b"]
        names = [na, nb]
        face = lambda n, side: world_bbox(n)[{"min": 0, "max": 1}[side]][ax]
        value = face(na, sa) - face(nb, sb)
    elif method == "bbox_span":
        names = [row["top"], row["bottom"]]
        value = world_bbox(row["top"])[1][ax] - world_bbox(row["bottom"])[0][ax]
    else:
        raise ValueError(f"unknown method: {method}")
    return value, names


def main():
    argv = sys.argv[sys.argv.index("--") + 1:]
    spec_path, out_path = argv[0], argv[1]
    with open(spec_path, encoding="utf-8") as f:
        spec = json.load(f)

    rows = []
    for row in spec["rows"]:
        rec = {"label": row["label"], "model_mm": None, "error": None, "objects": []}
        try:
            value, names = measure(row)
            rec["model_mm"] = value
            rec["objects"] = [object_info(n) for n in names]
        except (KeyError, IndexError, ValueError) as e:
            rec["error"] = f"{type(e).__name__}: {e}"
        rows.append(rec)

    out = {
        "blend": bpy.data.filepath,
        "blender_version": bpy.app.version_string,
        "rows": rows,
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print(f"measured {len(rows)} rows -> {out_path}")


main()
