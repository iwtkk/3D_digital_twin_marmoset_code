"""
Write the dataset overview table (LaTeX, tabularx) from the Release tree and config/dataset_overview_table.yaml.

Sizes (decimal GB) and the file count of the total are measured from --dataset-root; the text of every row comes from
the YAML. Warns when a row's folder holds extensions that its File format column does not list, and when a file of
the dataset is not covered by any row.

I/O ledger: scripts/07_package_dataset/io.md#make_dataset_overview_table

Example:
  .venv/bin/python scripts/07_package_dataset/make_dataset_overview_table.py \\
      --dataset-root /data/iwata/3D_digital_twin_marmoset_data_work_npz --out docs/dataset_overview.tex
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CFG = ROOT / "config/dataset_overview_table.yaml"
MULTI_EXT = (".nii.gz", ".seg.nrrd")


def ext_of(name: str) -> str:
    low = name.lower()
    return next((e for e in MULTI_EXT if low.endswith(e)), os.path.splitext(low)[1])


def walk(p: Path):
    """(path, size) of every file under p (p may be a file)."""
    if p.is_file():
        yield p, p.stat().st_size
        return
    for dp, _, fns in os.walk(p):
        for f in fns:
            q = Path(dp) / f
            yield q, q.stat().st_size


def fmt_gb(b: float) -> str:
    gb = b / 1e9
    return f"{gb:.1f}" if gb < 10 else f"{gb:,.0f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--dataset-root", type=Path, required=True)
    ap.add_argument("--config", type=Path, default=DEFAULT_CFG)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config))
    ignore = set(cfg.get("ignore_ext", []))

    covered = set()
    body = []
    for gi, g in enumerate(cfg["groups"]):
        if gi:
            body.append(r"\midrule")
        for ri, r in enumerate(g["rows"]):
            size, exts = 0, set()
            for rel in r["paths"]:
                p = a.dataset_root / rel
                if not p.exists():
                    raise SystemExit(f"missing in the dataset: {rel}")
                for q, s in walk(p):
                    size += s
                    covered.add(q)
                    exts.add(ext_of(q.name))
            extra = sorted(exts - set(r["formats"]) - ignore)
            unused = sorted(set(r["formats"]) - exts)
            if extra or unused:
                print(f"WARNING {r['paths'][0]}: not listed {extra}, listed but absent {unused}")
            folder = rf"\texttt{{{g['folder'].replace('_', chr(92) + '_')}}}" if ri == 0 else ""
            if ri:
                body.append(r"\cmidrule[0.2pt](l){2-6}")
            body.append(f" {folder} & {r['subfolder']} & {' '.join(r['contents'].split())} & "
                        f"{', '.join(r['formats'])} & {r['figure']} & {fmt_gb(size)}\\,GB \\\\")

    all_files = [(q, s) for q, s in walk(a.dataset_root)]
    rest = [q for q, _ in all_files if q not in covered]
    if rest:
        print(f"WARNING {len(rest)} files not covered by any row, e.g. {rest[0].relative_to(a.dataset_root)}")
    n_total, b_total = len(all_files), sum(s for _, s in all_files)

    today = dt.date.today().isoformat()
    out = [
        f"% Generated by scripts/07_package_dataset/make_dataset_overview_table.py from config/dataset_overview_table.yaml",
        f"% and {a.dataset_root} on {today} ({n_total:,} files, {b_total / 1e9:,.1f} GB, decimal GB). Do not edit by hand.",
        r"% Requires \usepackage{booktabs,tabularx}.",
        r"\begin{table*}[p]",
        r"\centering",
        rf"\caption{{{' '.join(cfg['caption'].split())}}}",
        rf"\label{{{cfg['label']}}}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{0.85}",
        r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{2.1cm}>{\raggedright\arraybackslash}p{2.9cm}"
        r">{\raggedright\arraybackslash}X>{\raggedright\arraybackslash}p{1.6cm}>{\raggedright\arraybackslash}p{1.5cm}r@{}}",
        r"\toprule",
        r"Top-level folder & Subfolder & Contents & File format & Figure / Section & Size \\",
        r"\midrule",
        *body,
        r"\midrule",
        rf"\multicolumn{{5}}{{@{{}}l}}{{Total ({n_total:,} files)}} & {b_total / 1e9:,.0f}\,GB \\",
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table*}",
    ]
    a.out.write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}: {n_total:,} files, {b_total / 1e9:,.1f} GB")


if __name__ == "__main__":
    main()
